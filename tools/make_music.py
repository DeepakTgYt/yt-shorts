"""Synthesize the reel background loops in bank/music/ from scratch (numpy only).

Every sound here is generated by this script: no samples, no third-party
recordings, so the tracks are original works and copyright-safe.
Run:  python tools/make_music.py   (needs numpy + ffmpeg; output is committed, not built on CI)
"""
import os, subprocess, wave
import numpy as np

SR = 44100
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bank", "music")
NOTE = lambda n: 440.0 * 2 ** ((n - 69) / 12)  # midi -> Hz


def env(n, a=0.005, d=0.25, s=0.0, r=0.05):
    t = np.arange(n) / SR
    e = np.where(t < a, t / a, s + (1 - s) * np.exp(-(t - a) / max(d, 1e-3)))
    rl = int(r * SR)
    if rl and rl < n:
        e[-rl:] *= np.linspace(1, 0, rl)
    return e


def osc(f, n, kind="saw", detune=0.0):
    t = np.arange(n) / SR
    ph = (f * (1 + detune)) * t
    if kind == "sine":
        return np.sin(2 * np.pi * ph)
    if kind == "square":
        return np.sign(np.sin(2 * np.pi * ph)) * 0.6
    if kind == "tri":
        return 2 * np.abs(2 * (ph % 1) - 1) - 1
    return 2 * (ph % 1) - 1  # saw


def lowpass(x, cut):
    a = np.exp(-2 * np.pi * cut / SR)
    y = np.empty_like(x); acc = 0.0
    for i, v in enumerate(x):  # one-pole, fine for short clips
        acc = (1 - a) * v + a * acc; y[i] = acc
    return y


def kick(n):
    t = np.arange(n) / SR
    f = 50 + 110 * np.exp(-t * 30)
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9)


def hat(n, rng):
    x = rng.standard_normal(n); x = x - lowpass(x, 6000)
    return x * env(n, 0.001, 0.03)


def clap(n, rng):
    x = rng.standard_normal(n); x = x - lowpass(x, 1200)
    return x * env(n, 0.002, 0.08) * 0.8


def track(seed, bpm, root, prog, scale, style, secs=12.0):
    rng = np.random.default_rng(seed)
    n = int(secs * SR); mix = np.zeros(n)
    beat = 60 / bpm; bar = 4 * beat; step = beat / 4
    def put(sig, t0, gain):
        i = int(t0 * SR)
        if i >= n: return
        j = min(n, i + len(sig)); mix[i:j] += gain * sig[: j - i]
    nbars = int(secs / bar) + 1
    for b in range(nbars):
        chord = prog[b % len(prog)]
        t_bar = b * bar
        # pad: soft detuned saws through a lowpass
        pl = int(bar * SR)
        pad = sum(osc(NOTE(root + chord + iv), pl, "saw", dt) for iv in (0, scale[2], 7) for dt in (-0.003, 0.003))
        put(lowpass(pad, 1400) * env(pl, 0.08, 2.0, 0.6, 0.15), t_bar, 0.08)
        for s16 in range(16):
            t = t_bar + s16 * step
            if s16 % 4 == 0: put(kick(int(0.35 * SR)), t, 0.6)
            if style != "chill" and s16 % 8 == 4: put(clap(int(0.2 * SR), rng), t, 0.35)
            if s16 % 2 == 1: put(hat(int(0.06 * SR), rng), t, 0.18 if style != "chill" else 0.1)
            # bass on 8ths with offbeat push
            if s16 % 2 == 0 and (style != "chill" or s16 % 4 == 0):
                bl = int(step * 2 * SR * 0.9)
                put(lowpass(osc(NOTE(root - 24 + chord), bl, "saw"), 500) * env(bl, 0.004, 0.18, 0.3, 0.02), t, 0.35)
            # arpeggio pluck from the scale over the chord
            pat = [0, 2, 4, 2, 5, 4, 2, 4] if style == "pop" else [0, 4, 7, 4, 9, 7, 4, 2]
            if style == "chill" and s16 % 2: continue
            deg = pat[s16 % len(pat)]
            semis = scale[deg % len(scale)] + 12 * (deg // len(scale))
            al = int(step * SR * 1.6)
            kind = {"pop": "square", "dance": "saw", "chill": "tri", "festive": "square"}[style]
            put(lowpass(osc(NOTE(root + 12 + chord + semis), al, kind), 3500) * env(al, 0.002, 0.12), t, 0.14)
    # gentle sidechain-ish pump on everything but drums is skipped for simplicity; just limit
    mix = np.tanh(mix * 1.2)
    mix /= np.max(np.abs(mix)) + 1e-9
    st = np.stack([mix, np.roll(mix, int(0.011 * SR)) * 0.97], 1)  # cheap stereo width
    return (st * 0.89 * 32767).astype(np.int16)


MAJ = [0, 2, 4, 5, 7, 9, 11]; MIN = [0, 2, 3, 5, 7, 8, 10]
TRACKS = [
    ("01_upbeat_pop", 1, 118, 60, [0, 7, 9, 5], MAJ, "pop"),         # C: I-V-vi-IV
    ("02_energy_dance", 2, 124, 57, [0, 8, 3, 10], MIN, "dance"),     # Am: i-VI-III-VII
    ("03_bright_chill", 3, 96, 62, [0, 5, 9, 7], MAJ, "chill"),       # D: I-IV-vi-V
    ("04_festive_bounce", 4, 128, 55, [0, 5, 7, 5], MAJ, "festive"),  # G: I-IV-V-IV
]

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name, seed, bpm, root, prog, scale, style in TRACKS:
        pcm = track(seed, bpm, root, prog, scale, style)
        wav = f"/tmp/{name}.wav"
        with wave.open(wav, "wb") as w:
            w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", wav, "-af", "loudnorm=I=-16:TP=-1.5:LRA=11",
                        "-ar", "44100", "-c:a", "aac", "-b:a", "128k", os.path.join(OUT, name + ".m4a")], check=True)
        print("wrote", name)
