"""Digits -> spoken Hindi words, for TTS engines that garble numerals (OmniVoice).
"1993 में 182वाँ" -> "उन्नीस सौ तिरानवे में एक सौ बयासीवाँ"."""
import re

_U = ("शून्य एक दो तीन चार पाँच छह सात आठ नौ दस ग्यारह बारह तेरह चौदह पंद्रह सोलह सत्रह अठारह उन्नीस बीस "
      "इक्कीस बाईस तेईस चौबीस पच्चीस छब्बीस सत्ताईस अट्ठाईस उनतीस तीस इकतीस बत्तीस तैंतीस चौंतीस पैंतीस छत्तीस "
      "सैंतीस अड़तीस उनतालीस चालीस इकतालीस बयालीस तैंतालीस चवालीस पैंतालीस छियालीस सैंतालीस अड़तालीस उनचास पचास "
      "इक्यावन बावन तिरपन चौवन पचपन छप्पन सत्तावन अट्ठावन उनसठ साठ इकसठ बासठ तिरसठ चौंसठ पैंसठ छियासठ सड़सठ "
      "अड़सठ उनहत्तर सत्तर इकहत्तर बहत्तर तिहत्तर चौहत्तर पचहत्तर छिहत्तर सतहत्तर अठहत्तर उन्यासी अस्सी इक्यासी "
      "बयासी तिरासी चौरासी पचासी छियासी सत्तासी अट्ठासी नवासी नब्बे इक्यानवे बानवे तिरानवे चौरानवे पंचानवे छियानवे "
      "सत्तानवे अट्ठानवे निन्यानवे").split()
assert len(_U) == 100


def words(n):
    if n < 100:
        return _U[n]
    if 1100 <= n <= 1999 and n % 100 and n % 1000 >= 100:  # years / "पंद्रह सौ" style
        return f"{_U[n // 100]} सौ" + (f" {_U[n % 100]}" if n % 100 else "")
    out = []
    for div, name in ((10 ** 7, "करोड़"), (10 ** 5, "लाख"), (1000, "हज़ार"), (100, "सौ")):
        if n >= div:
            out.append(f"{words(n // div)} {name}"); n %= div
    if n:
        out.append(_U[n])
    return " ".join(out)


_DEV = str.maketrans("०१२३४५६७८९", "0123456789")


def speak_numbers(text):
    t = text.translate(_DEV)
    t = re.sub(r"(?<=\d),(?=\d)", "", t)
    t = re.sub(r"(\d+)\s*[-–]\s*(\d+)", r"\1 से \2", t)
    t = re.sub(r"₹\s*(\d+)", r"\1 रुपये", t)
    t = re.sub(r"(\d+)\s*%", r"\1 प्रतिशत", t)
    t = re.sub(r"(\d+)\.(\d+)", lambda m: f"{words(int(m[1]))} दशमलव " + " ".join(_U[int(c)] for c in m[2]), t)
    return re.sub(r"\d+", lambda m: words(int(m[0])) if len(m[0]) <= 9 else " ".join(_U[int(c)] for c in m[0]), t)
